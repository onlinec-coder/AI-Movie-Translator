
import json
import subprocess
from pathlib import Path
from datetime import datetime, timezone


ROOT = Path(__file__).resolve().parents[2]

VIDEO_FILE = ROOT / "data" / "input" / "Husbands.mp4"
MEDIA_METADATA_FILE = ROOT / "data" / "output" / "media_metadata.json"

OUTPUT_DIR = ROOT / "data" / "output" / "visual_frames"
FRAME_METADATA_FILE = OUTPUT_DIR / "frame_metadata.json"

FRAME_INTERVAL = 1.0


def run_command(command):
    result = subprocess.run(
        command,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace"
    )

    if result.returncode != 0:
        raise RuntimeError(
            "FFmpeg command failed:\n"
            + " ".join(command)
            + "\n\n"
            + result.stderr[-5000:]
        )

    return result


def load_media_metadata():
    if not MEDIA_METADATA_FILE.exists():
        raise FileNotFoundError(MEDIA_METADATA_FILE)

    with open(MEDIA_METADATA_FILE, "r", encoding="utf-8") as f:
        metadata = json.load(f)

    duration = metadata.get(
        "analysis_window", {}
    ).get("extraction_duration_seconds")

    if duration is None or float(duration) <= 0:
        raise ValueError(
            "Invalid extraction duration in media_metadata.json"
        )

    return float(duration)


def extract_frames(duration):
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    # Delete only frames generated by this module.
    for old_frame in OUTPUT_DIR.glob("visual_frame_*.jpg"):
        old_frame.unlink()

    output_pattern = OUTPUT_DIR / "visual_frame_%06d.jpg"

    print("Extracting visual frames with FFmpeg...")

    run_command([
        "ffmpeg",
        "-y",
        "-i", str(VIDEO_FILE),
        "-t", str(duration),
        "-vf", "fps=1",
        "-q:v", "2",
        "-start_number", "1",
        str(output_pattern)
    ])

    return sorted(
        OUTPUT_DIR.glob("visual_frame_*.jpg")
    )


def main():
    print("VIDEO FRAME SAMPLER V1")
    print("----------------------")

    if not VIDEO_FILE.exists():
        raise FileNotFoundError(VIDEO_FILE)

    print("Loading media metadata...")
    duration = load_media_metadata()

    print(f"Video: {VIDEO_FILE.name}")
    print(f"Extraction duration: {duration} seconds")
    print(f"Frame interval: {FRAME_INTERVAL} second")

    frames = extract_frames(duration)

    if not frames:
        raise RuntimeError("No frames were extracted.")

    frame_records = []

    for index, frame_path in enumerate(frames):
        timestamp = round(index * FRAME_INTERVAL, 3)

        frame_records.append({
            "frame_id": f"VF_{index + 1:06d}",
            "timestamp_seconds": timestamp,
            "filename": frame_path.name,
            "path": str(frame_path)
        })

    metadata = {
        "schema_version": "1.0.0",
        "engine_version": "1.0.0",
        "created_at": datetime.now(timezone.utc).isoformat(),
        "source": {
            "video": str(VIDEO_FILE),
            "media_metadata": str(MEDIA_METADATA_FILE)
        },
        "sampling": {
            "method": "FIXED_INTERVAL",
            "interval_seconds": FRAME_INTERVAL,
            "extraction_duration_seconds": duration
        },
        "statistics": {
            "total_frames": len(frames),
            "first_frame_seconds": frame_records[0]["timestamp_seconds"],
            "last_frame_seconds": frame_records[-1]["timestamp_seconds"]
        },
        "frames": frame_records
    }

    with open(FRAME_METADATA_FILE, "w", encoding="utf-8") as f:
        json.dump(
            metadata,
            f,
            ensure_ascii=False,
            indent=2
        )

    print("\nFRAME SAMPLING: OK")
    print("------------------")
    print("Total frames:", len(frames))
    print("First frame:", frame_records[0]["timestamp_seconds"])
    print("Last frame:", frame_records[-1]["timestamp_seconds"])
    print("Output directory:", OUTPUT_DIR)
    print("Metadata:", FRAME_METADATA_FILE)


if __name__ == "__main__":
    main()
